import fs from 'node:fs';
import path from 'node:path';
import { analyzeHtml } from './audit.js';
import { findHtmlFiles, fileToUrl } from './site.js';
import { lastCommitDate } from './git.js';
import { escapeAttr, escapeHtml, truncate, today } from './util.js';

export const SITEMAP_MARKER = 'generated by seo-autopilot';

// Add whatever SEO tags a page is missing. Existing tags are never touched, so it is safe to re-run.
// `template` is for single-page-app shells, where per-URL tags (canonical, og:url) would be wrong.
export function fixHtml(html, { pageUrl, isHome, siteName, siteDescription, lang, ogImage, template = false }) {
  const changes = [];
  const headOpen = html.match(/<head(\s[^>]*)?>/i);
  if (!headOpen || !/<\/head\s*>/i.test(html)) return { html, changes };
  const p = analyzeHtml(html, pageUrl);
  if (p.noindex) return { html, changes }; // intentionally hidden page

  const afterOpen = html.slice(headOpen.index + headOpen[0].length);
  const indent = afterOpen.match(/^[^\S\n]*\n([ \t]*)\S/)?.[1] ?? '    ';
  const tags = [];
  if (!p.viewport) { tags.push('<meta name="viewport" content="width=device-width, initial-scale=1">'); changes.push('viewport'); }

  let title = p.title;
  let out = html;
  if (!title) {
    title = isHome ? siteName || p.h1s[0] : [p.h1s[0], siteName].filter(Boolean).join(' | ');
    if (title) {
      if (p.hasTitleTag) out = out.replace(/<title(\s[^>]*)?>\s*<\/title>/i, `<title>${escapeHtml(title)}</title>`);
      else tags.push(`<title>${escapeHtml(title)}</title>`);
      changes.push('title');
    }
  }

  let desc = p.description;
  if (desc === null) {
    desc = isHome && siteDescription ? siteDescription : p.firstParagraph ? truncate(p.firstParagraph, 155) : null;
    if (desc) { tags.push(`<meta name="description" content="${escapeAttr(desc)}">`); changes.push('meta description'); }
  }

  if (!p.canonical && !template) { tags.push(`<link rel="canonical" href="${escapeAttr(pageUrl)}">`); changes.push('canonical'); }

  const og = [];
  if (!p.og.type) og.push(['og:type', 'website']);
  if (!p.og.title && title) og.push(['og:title', title]);
  if (!p.og.description && desc) og.push(['og:description', desc]);
  if (!p.og.url && !template) og.push(['og:url', pageUrl]);
  if (!p.og.siteName && siteName) og.push(['og:site_name', siteName]);
  if (!p.og.image && ogImage) og.push(['og:image', new URL(ogImage, pageUrl).toString()]);
  for (const [prop, val] of og) tags.push(`<meta property="${prop}" content="${escapeAttr(val)}">`);
  if (og.length) changes.push('Open Graph');
  if (!p.twitterCard) {
    tags.push(`<meta name="twitter:card" content="${p.og.image || ogImage ? 'summary_large_image' : 'summary'}">`);
    changes.push('Twitter card');
  }

  if (isHome && !p.jsonLd && siteName) {
    const data = { '@context': 'https://schema.org', '@type': 'WebSite', name: siteName, url: pageUrl, ...(siteDescription && { description: siteDescription }) };
    tags.push(`<script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`);
    changes.push('structured data');
  }

  if (tags.length) {
    const idx = out.search(/<\/head\s*>/i);
    const before = out.slice(0, idx);
    const closeIndent = before.match(/\n([ \t]*)$/)?.[1] ?? '';
    const head = before.replace(/[ \t]*$/, '');
    const block = ['<!-- SEO tags added by seo-autopilot -->', ...tags].map((t) => indent + t).join('\n');
    out = `${head}${head.endsWith('\n') ? '' : '\n'}${block}\n${closeIndent}${out.slice(idx)}`;
  }
  // charset must come first in <head>, so it goes right after the opening tag.
  if (!p.charset) {
    const sameLine = !/^[^\S\n]*\n/.test(afterOpen);
    out = out.replace(/<head(\s[^>]*)?>/i, (m) => `${m}\n${indent}<meta charset="utf-8">${sameLine ? `\n${indent}` : ''}`);
    changes.unshift('charset');
  }
  if (!p.lang && lang) {
    out = out.replace(/<html\b([^>]*)>/i, (m, attrs) => `<html lang="${escapeAttr(lang)}"${attrs}>`);
    changes.push('lang');
  }
  return { html: out, changes, noindex: false };
}

export function buildSitemap(entries) {
  const lines = ['<?xml version="1.0" encoding="UTF-8"?>', `<!-- ${SITEMAP_MARKER} -->`, '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'];
  for (const e of entries) {
    lines.push('  <url>', `    <loc>${escapeHtml(e.loc)}</loc>`);
    if (e.lastmod) lines.push(`    <lastmod>${e.lastmod}</lastmod>`);
    lines.push('  </url>');
  }
  lines.push('</urlset>', '');
  return lines.join('\n');
}

export function updateRobots(existing, sitemapUrl) {
  if (existing == null) return `User-agent: *\nAllow: /\n\nSitemap: ${sitemapUrl}\n`;
  if (existing.includes(sitemapUrl)) return existing;
  return `${existing.replace(/\s*$/, '')}\n\nSitemap: ${sitemapUrl}\n`;
}

// /about, /about.html and /about/ are the same page for sitemap purposes.
const pageKey = (u) => u.replace(/(index)?\.html?$/i, '').replace(/\/$/, '');

/**
 * Apply all local changes: HTML tag fixes, sitemap.xml, robots.txt and any verification/key files.
 * Returns the changed paths (relative to dirAbs) so the caller can commit exactly those.
 */
export function applyFixes({ dirAbs, project, site, cfg, crawledPages = [], extraFiles = [], htmlFixes = true, sitemap = true, replaceSitemap = false, dryRun = false }) {
  const publishAbs = path.resolve(dirAbs, cfg.publishDir || '.');
  const rel = (abs) => path.relative(dirAbs, abs).split(path.sep).join('/');
  const changed = new Set();
  const pageChanges = [];
  const notes = [];
  const write = (abs, content) => {
    if (!dryRun) {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
    }
    changed.add(rel(abs));
  };
  const ctx = { siteName: cfg.siteName, siteDescription: cfg.siteDescription, lang: cfg.lang, ogImage: cfg.ogImage };

  const localPages = [];
  if (project.kind === 'framework') {
    if (htmlFixes) {
      const templates = ['index.html', 'public/index.html', 'src/index.html'].map((f) => path.join(dirAbs, f)).filter((f) => fs.existsSync(f));
      for (const file of templates) {
        const { html, changes } = fixHtml(fs.readFileSync(file, 'utf8'), { ...ctx, pageUrl: site.url, isHome: true, template: true });
        if (changes.length) { write(file, html); pageChanges.push({ file: rel(file), changes }); }
      }
      notes.push(`${project.framework} project: only the HTML shell was edited. Set per-page titles and descriptions in your ${project.framework} head/metadata code.`);
    }
  } else {
    for (const file of findHtmlFiles(publishAbs)) {
      const name = path.basename(file).toLowerCase();
      if (name === '404.html' || /^google[0-9a-f]+\.html$/.test(name)) continue;
      const pageUrl = fileToUrl(site.url, publishAbs, file);
      const original = fs.readFileSync(file, 'utf8');
      const { html, changes } = htmlFixes ? fixHtml(original, { ...ctx, pageUrl, isHome: pageUrl === site.url }) : { html: original, changes: [] };
      if (changes.length) { write(file, html); pageChanges.push({ file: rel(file), changes }); }
      if (!analyzeHtml(html, pageUrl).noindex) localPages.push({ loc: pageUrl, file, changed: changes.length > 0 });
    }
    if (project.framework === 'Jekyll') notes.push('Jekyll site: pages built from Markdown or layouts were not edited. Consider adding the jekyll-seo-tag plugin.');
  }

  let sitemapUrl = new URL('sitemap.xml', site.url).toString();
  let sitemapEntries = [];
  if (sitemap) {
    const entries = new Map();
    for (const p of localPages) {
      const lastmod = p.changed ? today() : lastCommitDate(dirAbs, p.file) || fs.statSync(p.file).mtime.toISOString().slice(0, 10);
      entries.set(pageKey(p.loc), { loc: p.loc, lastmod });
    }
    for (const p of crawledPages) {
      if (p.kind === 'html' && !p.noindex && p.url.startsWith(site.url) && !entries.has(pageKey(p.url))) entries.set(pageKey(p.url), { loc: p.url });
    }
    if (!entries.size) entries.set(pageKey(site.url), { loc: site.url, lastmod: today() }); // e.g. a single-page app
    sitemapEntries = [...entries.values()].sort((a, b) => (a.loc === site.url ? -1 : b.loc === site.url ? 1 : a.loc.localeCompare(b.loc)));

    const smAbs = path.join(publishAbs, 'sitemap.xml');
    const existing = fs.existsSync(smAbs) ? fs.readFileSync(smAbs, 'utf8') : null;
    if (existing && !existing.includes(SITEMAP_MARKER) && !replaceSitemap) {
      notes.push('Kept your existing sitemap.xml (pass --replace-sitemap to regenerate it).');
    } else if (sitemapEntries.length) {
      const xml = buildSitemap(sitemapEntries);
      if (xml !== existing) write(smAbs, xml);
    } else {
      notes.push('No pages found for a sitemap.');
    }

    if (site.isRoot) {
      const robotsAbs = path.join(publishAbs, 'robots.txt');
      const existingRobots = fs.existsSync(robotsAbs) ? fs.readFileSync(robotsAbs, 'utf8') : null;
      const next = updateRobots(existingRobots, sitemapUrl);
      if (next !== existingRobots) write(robotsAbs, next);
    }
  }

  for (const f of extraFiles) {
    const abs = path.join(publishAbs, f.name);
    if (!fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== f.content) write(abs, f.content);
  }

  return { changed: [...changed], pageChanges, notes, sitemapUrl, sitemapEntries };
}
